/** Screen size on the card. Cells are square, so a round subject stays round. */
const CELL = 2.0;

/**
 * How much of the measured disc to keep. Slightly inside the limb, because the
 * outermost ring of a photographed moon is half glow.
 */
const DISC = 0.97;

/**
 * Raises a colour towards white until it clears a minimum brightness.
 *
 * The moon's unlit limb traces out almost black, which against a black card is
 * no mark at all — and this needs a whole disc of dots for the terminator to
 * sweep across. Lifting keeps each cell's hue and only argues with its value.
 */
function lift(hex: string, min: number) {
  const n = Number.parseInt(hex.slice(1), 16);
  const r = (n >> 16) & 255;
  const g = (n >> 8) & 255;
  const b = n & 255;
  const lum = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  if (lum >= min) return hex;
  const k = min / Math.max(lum, 1);
  const to = (c: number) => Math.min(255, Math.round(c * k));
  return `#${((to(r) << 16) | (to(g) << 8) | to(b)).toString(16).padStart(6, "0")}`;
}

/** One fill-hold-drain-rest cycle, in milliseconds. */
const GROW_MS = 4000;
const HOLD_MS = 1000;
const DRAIN_MS = 2000;
const REST_MS = 400;
const CYCLE_MS = GROW_MS + HOLD_MS + DRAIN_MS + REST_MS;

function clamp(n: number, min: number, max: number) {
  return Math.min(max, Math.max(min, n));
}

/** The cubic-bezier(0.65, 0, 0.35, 1) ease-in-out, in closed form. */
function easeInOutCubic(p: number) {
  return p < 0.5 ? 4 * p * p * p : 1 - Math.pow(-2 * p + 2, 3) / 2;
}

function smoothstep(edge0: number, edge1: number, x: number) {
  const t = clamp((x - edge0) / (edge1 - edge0), 0, 1);
  return t * t * (3 - 2 * t);
}

/** Where an uncontrolled card sits, as a fraction, at time `ms`. */
function cycleAt(ms: number) {
  const t = ms % CYCLE_MS;
  if (t < GROW_MS) return easeInOutCubic(t / GROW_MS);
  if (t < GROW_MS + HOLD_MS) return 1;
  if (t < GROW_MS + HOLD_MS + DRAIN_MS) {
    return 1 - easeInOutCubic((t - GROW_MS - HOLD_MS) / DRAIN_MS);
  }
  return 0;
}

/**
 * Deterministic pseudo-random in [0, 1). Three jobs: deciding whether a cell
 * gets a mark at all, nudging marks off the lattice they were sampled on, and
 * setting the order they light in. `Math.random` would disagree between the
 * server render and the first client one; a pure function of its inputs cannot.
 */
function hash01(a: number, b: number) {
  // An integer bit-mixer rather than the usual fract(sin(dot(…))) trick. That
  // one is fine for a handful of samples but its output is strongly correlated
  // along rows once the inputs are pixel coordinates rather than small indices,
  // and on a grid this size it prints the correlation straight onto the picture
  // as horizontal banding. Quantising to a fixed grid first also keeps it
  // stable against floating-point drift between server and client.
  let h = Math.imul(Math.round(a * 4096) | 0, 0x27d4eb2d);
  h ^= Math.imul(Math.round(b * 4096) | 0, 0x165667b1);
  h = Math.imul(h ^ (h >>> 15), 0x85ebca6b);
  h = Math.imul(h ^ (h >>> 13), 0xc2b2ae35);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

type Mark = {
  cx: number;
  cy: number;
  /** How far across the disc this mark sits, 0 at the left limb and 1 at the right. */
  across: number;
  size: number;
  color: string;
  /** The fill this mark lights at. See the second pass below. */
  turn: number;
};

/**
 * The screened picture, laid down once at module load and shared by every card
 * on the page.
 *
 * Two things make this a stipple rather than a grid of squares. Whether a cell
 * gets a mark at all is a coin weighted by that cell's ink, so tone is a count
 * of marks per area — which is what the eye actually reads density as. And
 * every mark is nudged up to half a cell off true, which stops nine thousand of
 * them lining back up into the lattice they were sampled on.
 */
/**
 * Where the subject's disc actually is, measured off the photograph by the
 * tracer rather than assumed to fill the grid.
 *
 * Assuming it did is what drew two moons: a crescent's bounding box is far
 * taller than it is wide, so a circle centred on the grid comes out both offset
 * from the photographed limb and larger than it — and the floor below then
 * stipples that second, wrong circle in behind the real one.
 */
const DISC_CX = TRACE_DISC ? TRACE_DISC.x : (TRACE_COLS - 1) / 2;
const DISC_CY = TRACE_DISC ? TRACE_DISC.y : (TRACE_ROWS - 1) / 2;
const DISC_R =
  (TRACE_DISC ? TRACE_DISC.r : Math.min(TRACE_COLS, TRACE_ROWS) / 2) * DISC;

function buildPlate(stride: number, cell: number): Mark[] {
  const marks: Mark[] = [];
  // The canvas is the disc's bounding square, not the trace's — so the moon
  // arrives centred and at full size rather than sitting small and off to one
  // side of a mostly empty plate.
  const originX = DISC_CX - DISC_R;
  const originY = DISC_CY - DISC_R;

  for (let y = 0; y < TRACE_ROWS; y += stride) {
    for (let x = 0; x < TRACE_COLS; x += stride) {
      // The disc. Everything the photograph has outside it — sky, and the halo
      // of stray light around the limb — is thrown away: a moon is a circle,
      // and a ragged edge of glow would leave the terminator sweeping across a
      // shape that has no edge to arrive at.
      const nx = (x - DISC_CX) / DISC_R;
      const ny = (y - DISC_CY) / DISC_R;
      const r = Math.hypot(nx, ny);
      if (r > 1) continue;

      const i = y * TRACE_COLS + x;
      const traced = (TRACE_LEVELS.charCodeAt(i) - 48) / 9;
      // A floor under the whole disc. Half this moon is unlit and traces out
      // near black; without a floor that half is simply missing, and there is
      // nothing there for the terminator to move over.
      const v = Math.max(traced, 0.3);
      // Feather the limb, so the disc's edge is a scatter thinning out rather
      // than a cut circle.
      const edge = smoothstep(1, 0.9, r);
      if (hash01(x + 0.5, y + 0.5) > Math.pow(v, 0.7) * edge) continue;

      marks.push({
        cx: ((x - originX) / stride) * cell + (hash01(x, y * 1.7) - 0.5) * cell,
        cy: ((y - originY) / stride) * cell + (hash01(x * 2.3, y) - 0.5) * cell,
        // Measured across the disc rather than across the grid, so the sweep
        // starts exactly at the left limb and ends exactly at the right.
        across: clamp((nx + 1) / 2, 0, 1),
        // A little size on top of the density, so the brightest passages read
        // as solid rather than merely crowded.
        size: (0.6 + 0.5 * v) * cell,
        color: lift(
          TRACE_PALETTE[TRACE_COLORS.charCodeAt(i) - 48] ?? TRACE_PALETTE[0],
          78,
        ),
        turn: 0,
      });
    }
  }
  return marks;
}

/**
 * Second pass: the fill level each mark lights at.
 *
 * Mostly how far across the disc it sits, so the light crosses the moon left to
 * right the way a terminator does and 100% is the full moon. The rest is the
 * mark's own random number — enough scatter that the edge of the light is a
 * ragged band of dots rather than a ruled line, which is both truer to a real
 * terminator and the thing that stops this reading as a wipe.
 */
const RANDOMNESS = 0.24;
function setTurns(plate: Mark[]) {
  for (const m of plate) {
    m.turn = m.across * (1 - RANDOMNESS) + hash01(m.cx, m.cy) * RANDOMNESS;
  }
  return plate;
}

/** The moon at full size, and the same moon at glance size for the collapsed
 *  card — same trace, sampled every sixth cell so it stays a moon rather than
 *  turning to mud at 36 pixels. */
const PLATE = setTurns(buildPlate(1, CELL));
const PLATE_W = Math.round(2 * DISC_R * CELL);

const MINI_STRIDE = 6;
const MINI_CELL = 3.0;
const MINI = setTurns(buildPlate(MINI_STRIDE, MINI_CELL));
const MINI_W = Math.round(((2 * DISC_R) / MINI_STRIDE) * MINI_CELL);

/** Paints one frame of `plate` into a `size`-square canvas. */
function draw(
  ctx: CanvasRenderingContext2D,
  fraction: number,
  plate: Mark[],
  size: number,
) {
  ctx.clearRect(0, 0, size, size);

  // Bucket by colour first. Setting fillStyle thousands of times a frame is
  // what would make this expensive; setting it once per palette entry does not.
  const buckets = new Map<string, { cx: number; cy: number; size: number }[]>();
  const push = (color: string, cx: number, cy: number, size: number) => {
    let bucket = buckets.get(color);
    if (!bucket) buckets.set(color, (bucket = []));
    bucket.push({ cx, cy, size });
  };

  for (const mark of plate) {
    // Each mark lights on its own turn rather than as a front crossing it.
    // Size eases across the transition while the colour changes at the halfway
    // point, so a dot swells into being rather than appearing.
    const lit = smoothstep(mark.turn - 0.02, mark.turn + 0.02, fraction);
    push(
      lit > 0.5 ? mark.color : PALETTE.ghost,
      mark.cx,
      mark.cy,
      mark.size * (0.7 + 0.3 * lit),
    );
  }

  for (const [color, marks] of buckets) {
    ctx.fillStyle = color;
    ctx.beginPath();
    for (const { cx, cy, size } of marks) {
      ctx.rect(cx - size / 2, cy - size / 2, size, size);
    }
    ctx.fill();
  }
}

function usePrefersReducedMotion() {
  const [reduced, setReduced] = React.useState(false);
  React.useEffect(() => {
    const query = window.matchMedia("(prefers-reduced-motion: reduce)");
    const sync = () => setReduced(query.matches);
    sync();
    query.addEventListener("change", sync);
    return () => query.removeEventListener("change", sync);
  }, []);
  return reduced;
}

